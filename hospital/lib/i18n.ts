export type Translator = (message: string, values?: Record<string, string | number>) => string;

export const localeTags: Record<Locale, string> = { kk: "kk-KZ", ru: "ru-RU", en: "en-US" };

export function translate(locale: Locale, message: string, values: Record<string, string | number> = {}) {
  const match = message.includes("{") ? message : Object.keys(messages).find((template) => template.includes("{") && templatePattern(template).test(message));
  const template = match ?? message;
  let translated = locale === "ru" ? message : messages[template]?.[locale === "kk" ? 0 : 1] ?? message;
  if (match) {
    const pattern = templatePattern(match);
    const captures = message.match(pattern)?.slice(1) ?? [];
    const names = [...match.matchAll(/\{(\w+)\}/g)].map((entry) => entry[1]);
    names.forEach((name, index) => { if (!(name in values) && captures[index] !== undefined) values[name] = captures[index]; });
  }
  for (const [key, value] of Object.entries(values)) translated = translated.replaceAll(`{${key}}`, String(value));
  return translated;
}

const patternCache = new Map<string, RegExp>();
function templatePattern(template: string) {
  const cached = patternCache.get(template);
  if (cached) return cached;
  const escaped = template.split(/\{\w+\}/g).map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  const pattern = new RegExp(`^${escaped.join("(.+?)")}$`);
  patternCache.set(template, pattern);
  return pattern;
}
